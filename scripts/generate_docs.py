"""Generate the GitHub-readable reference without loading a model."""

import inspect
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import faster_tts


def docstring(obj):
    """Render Google-style sections as Markdown headings and lists."""
    parts = re.split(
        r"(?m)^(Args|Attributes|Returns|Raises|Example|Examples):\n",
        inspect.getdoc(obj) or "",
    )
    rendered = [parts[0].strip()]
    for title, body in zip(parts[1::2], parts[2::2]):
        body = textwrap.dedent(body).strip()
        if title not in ("Example", "Examples"):
            body = re.sub(r"(?m)^([^\s:][^\n:]*):", r"- **\1**:", body)
        rendered.append(f"**{title}**\n\n{body}")
    return "\n\n".join(rendered)


def signature(name, obj):
    """Render signatures with one parameter per line when long."""
    sig = inspect.signature(obj)
    parameters = dict(sig.parameters)
    parameters.pop("self", None)
    sig = sig.replace(parameters=parameters.values())
    if len(name + str(sig)) <= 88:
        return name + str(sig)
    lines = []
    previous_kind = None
    for parameter in sig.parameters.values():
        if parameter.kind == inspect.Parameter.KEYWORD_ONLY and previous_kind not in (
            inspect.Parameter.KEYWORD_ONLY,
            inspect.Parameter.VAR_POSITIONAL,
        ):
            lines.append("    *,")
        lines.append(f"    {parameter},")
        previous_kind = parameter.kind
    suffix = str(sig)[str(sig).rfind(")") + 1 :]
    return name + "(\n" + "\n".join(lines) + "\n)" + suffix


def generate():
    """Document every exported class, including inherited public methods."""
    sections = [
        "# Python API reference",
        "<!-- Generated by scripts/generate_docs.py. Edit source docstrings. -->",
        "\n".join(f"- [{name}](#{name.lower()})" for name in faster_tts.__all__),
    ]
    for name in faster_tts.__all__:
        cls = getattr(faster_tts, name)
        sections.extend(
            [f"## {name}", f"```python\n{signature(name, cls)}\n```", docstring(cls)]
        )
        for method_name, method in inspect.getmembers(cls, inspect.isfunction):
            if method_name.startswith("_"):
                continue
            qualified = f"{name}.{method_name}"
            sections.extend(
                [
                    f"### {qualified}",
                    f"```python\n{signature(qualified, method)}\n```",
                    docstring(method),
                ]
            )
    return "\n\n".join(sections) + "\n"


if __name__ == "__main__":
    (ROOT / "docs" / "api.md").write_text(generate(), encoding="utf-8")
